// Take user input and print their sums 

int main(){
    int a, b;
    printf("Enter first digit : ");
    scanf("%d", &a);
    printf("Enter the second digit : ");
    scanf("%d", &b);
    int sum = a + b;
    printf("The sum is : %d", sum);
    return 0;
}